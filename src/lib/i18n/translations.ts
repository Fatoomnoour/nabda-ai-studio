export function localizeValidationMessage(message: string | null, lang: Lang): string | null {
  if (!message || lang === "ar") return message;
  return ARABIC_TO_ENGLISH_ERRORS[message] ?? message;
}

export function formatLocalizedDate(iso: string, lang: Lang): string {
  try {
    return new Intl.DateTimeFormat(lang === "en" ? "en-US" : "ar-SA", {
      dateStyle: "medium",
      timeStyle: "short",
    }).format(new Date(iso));
  } catch {
    return iso;
  }
}

export function localizeApprovalLabel(label: string, lang: Lang): string {
  if (lang === "ar") return label;
  return WORKSPACE_EN.approvalLabels[label] ?? label;
}
