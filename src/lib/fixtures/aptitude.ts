export function extractDemoFacts(source: string): SourceFact[] {
  return SOURCE_QUOTES.flatMap((quote, i) => {
    const start = source.indexOf(quote);
    return start < 0 ? [] : [{ id: `fact_${i + 1}`, statement: quote, quote, start, end: start + quote.length, state: "supported" as const }];
  });
}

